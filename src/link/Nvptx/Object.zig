//! This file holds a PTX module in MIR form. `emit` writes the PTX of the module. `write` stores
//! the module in an NVPTX object, the output of `zig build-obj`. `read` loads the object for the
//! linker. The linker inlines and removes functions across objects.

const std = @import("std");
const Allocator = std.mem.Allocator;
const Io = std.Io;
const assert = std.debug.assert;
const native_endian = @import("builtin").cpu.arch.endian();
const Mir = @import("../../codegen/nvptx/Mir.zig");
const Lower = @import("../../codegen/nvptx/Lower.zig");
const Emit = @import("../../codegen/nvptx/Emit.zig");
const tracy = @import("../../tracy.zig");
const Object = @This();

ptx_version: u16,
target: []const u8,
address_size: u16,
/// This field holds the version of the Zig compiler that wrote the object.
compiler: []const u8,
externs: []Item,
data: []Item,
functions: []Item,
aliases: []const Alias,
names: []const []const u8,
/// The positions in `functions` of the functions that `emit` lists in a table of function
/// addresses, so that ptxas keeps each of them (`ltcg.addressTable`).
table: []const u32 = &.{},

pub const Item = struct {
    mir: Mir,
    linkage: Linkage,
};

/// An alias is a second name of a function in `functions`. The module declares the alias with
/// `.alias`. ptxas gives the alias the linkage of its function.
pub const Alias = struct {
    name: Mir.Target,
    function: u32,
};

pub const Linkage = enum { local, visible, @"extern" };

/// The first byte is not text. Therefore no text file starts with these bytes.
pub const magic = "\x7fZigNVPTXObject\x00";

/// The layout can change without a new version. `read` can then misparse an older object.
pub const format_version: u32 = 1;

/// The header pads the CPU model name with zeros to this length.
pub const target_len = 16;

pub const ReadError = Allocator.Error || error{InvalidObject};

pub fn deinit(object: *Object, gpa: Allocator) void {
    for ([_][]Item{ object.externs, object.data, object.functions }) |items| {
        for (items) |*item| item.mir.deinit(gpa);
        gpa.free(items);
    }
    gpa.free(object.aliases);
    for (object.names) |name| gpa.free(name);
    gpa.free(object.names);
    gpa.free(object.target);
    gpa.free(object.compiler);
    object.* = undefined;
}

/// Writes the PTX of the module. `names.writeName(w, target)` writes the name of each `Mir.Target`.
pub fn emit(object: *const Object, gpa: Allocator, w: *Io.Writer, names: anytype) !void {
    try w.print(
        \\//
        \\// Generated by the Zig compiler
        \\//
        \\
        \\.version {d}.{d}
        \\.target {s}
        \\.address_size {d}
        \\
        \\
    , .{ object.ptx_version / 10, object.ptx_version % 10, object.target, object.address_size });
    for (object.externs) |item| {
        try (Emit{ .mir = &item.mir, .writer = w }).text(names, 0, item.mir.text.len);
        try w.writeAll(";\n");
    }
    // ptxas rejects a call before the declaration or definition of its callee. ptxas also rejects
    // a call to an entry point. Therefore only functions need a declaration.
    for (object.functions) |item| {
        if (item.mir.kind != .func) continue;
        try writeLinkage(w, item.linkage);
        try (Emit{ .mir = &item.mir, .writer = w }).text(names, 0, item.mir.prototype_len);
        try w.writeAll(";\n");
    }
    // PTX ISA 9.4, section 11.2.3: the alias needs a declaration with the prototype of the
    // function.
    for (object.aliases) |alias| {
        const function = &object.functions[alias.function];
        const name = function.mir.relocs[0];
        assert(function.mir.relocs.len == 1 or function.mir.relocs[1].offset >= function.mir.prototype_len);
        try writeLinkage(w, function.linkage);
        try w.writeAll(function.mir.text[0..name.offset]);
        try names.writeName(w, alias.name);
        try w.writeAll(function.mir.text[name.offset..function.mir.prototype_len]);
        try w.writeAll(";\n.alias ");
        try names.writeName(w, alias.name);
        try w.writeAll(", ");
        try names.writeName(w, name.target);
        try w.writeAll(";\n");
    }
    if (object.table.len != 0) {
        try w.print(".global .align {d} .u{d} __zig_function_table[{d}] = {{", .{ object.address_size / 8, object.address_size, object.table.len });
        for (object.table, 0..) |function, i| {
            if (i != 0) try w.writeAll(", ");
            try names.writeName(w, object.functions[function].mir.relocs[0].target);
        }
        try w.writeAll("};\n");
    }
    try w.writeAll("\n");
    for (object.data) |item| {
        try writeLinkage(w, item.linkage);
        try (Emit{ .mir = &item.mir, .writer = w }).text(names, 0, item.mir.text.len);
    }
    for (object.functions) |item| {
        try w.writeAll("\n");
        try writeLinkage(w, item.linkage);
        try (Emit{ .mir = &item.mir, .writer = w }).text(names, 0, item.mir.text.len);
        const lower_trace = tracy.traceNamed(@src(), "NVPTX register assignment");
        lower_trace.setValue(item.mir.instructions.len);
        var registers = try Lower.run(gpa, &item.mir);
        lower_trace.end();
        defer {
            registers.instructions.deinit(gpa);
            gpa.free(registers.extra);
        }
        const text_trace = tracy.traceNamed(@src(), "NVPTX PTX text");
        defer text_trace.end();
        try (Emit{ .mir = &registers, .writer = w }).body(names);
    }
}

fn writeLinkage(w: *Io.Writer, linkage: Linkage) !void {
    if (linkage == .visible) try w.writeAll(".visible ");
}

/// Writes the name of a `.name` target of an object from `read`.
pub fn writeName(object: *const Object, w: *Io.Writer, target: Mir.Target) !void {
    try w.writeAll(object.names[target.name]);
}

pub fn nameIndex(object: *const Object, target: Mir.Target) u32 {
    _ = object;
    return target.name;
}

/// Writes the module as a little-endian NVPTX object. The host must be little-endian.
/// `names.nameIndex(target)` returns the index of each `Mir.Target` in `object.names`.
pub fn write(object: *const Object, w: *Io.Writer, names: anytype) Io.Writer.Error!void {
    assert(native_endian == .little);
    assert(object.target.len <= target_len);
    try w.writeAll(magic);
    try w.writeInt(u32, format_version, .little);
    try w.writeInt(u16, object.ptx_version, .little);
    try w.writeInt(u16, object.address_size, .little);
    var target: [target_len]u8 = @splat(0);
    @memcpy(target[0..object.target.len], object.target);
    try w.writeAll(&target);
    try writeBytes(w, object.compiler);
    try writeLen(w, object.names.len);
    for (object.names) |name| try writeBytes(w, name);
    for ([_][]const Item{ object.externs, object.data, object.functions }) |items| {
        try writeLen(w, items.len);
        for (items) |*item| {
            try w.writeByte(@backingInt(item.linkage));
            try writeMir(w, &item.mir, names);
        }
    }
    try writeLen(w, object.aliases.len);
    for (object.aliases) |alias| {
        try w.writeInt(u32, names.nameIndex(alias.name), .little);
        try w.writeInt(u32, alias.function, .little);
    }
}

fn writeMir(w: *Io.Writer, mir: *const Mir, names: anytype) Io.Writer.Error!void {
    try w.writeByte(@backingInt(mir.kind));
    try w.writeByte(@intFromBool(mir.is_noinline));
    try w.writeInt(u16, mir.ptx_version, .little);
    try writeBytes(w, mir.text);
    try w.writeInt(u32, mir.prototype_len, .little);
    try writeLen(w, mir.relocs.len);
    for (mir.relocs) |reloc| {
        try w.writeInt(u32, reloc.offset, .little);
        try w.writeInt(u32, names.nameIndex(reloc.target), .little);
    }
    try w.writeAll(std.mem.sliceAsBytes(&mir.reg_counts));
    try w.writeInt(u32, mir.label_count, .little);
    const instructions = mir.instructions;
    try writeLen(w, instructions.len);
    for (instructions.items(.tag)) |tag| try w.writeByte(@backingInt(tag));
    for (instructions.items(.ty)) |ty| try w.writeByte(@backingInt(ty));
    try w.writeAll(std.mem.sliceAsBytes(instructions.items(.modifiers)));
    try w.writeAll(std.mem.sliceAsBytes(instructions.items(.data)));
    try writeLen(w, mir.extra.len);
    try w.writeAll(std.mem.sliceAsBytes(mir.extra));
    try writeBytes(w, mir.strings);
    try writeLen(w, mir.symbols.len);
    for (mir.symbols) |symbol| {
        try w.writeInt(u32, names.nameIndex(symbol.target), .little);
        try w.writeInt(u64, symbol.offset, .little);
    }
    try writeLen(w, mir.locals.len);
    for (mir.locals) |local| {
        try w.writeInt(u64, local.size, .little);
        try w.writeInt(u64, local.alignment, .little);
    }
}

fn writeLen(w: *Io.Writer, len: usize) Io.Writer.Error!void {
    try w.writeInt(u32, @intCast(len), .little);
}

fn writeBytes(w: *Io.Writer, bytes: []const u8) Io.Writer.Error!void {
    try writeLen(w, bytes.len);
    try w.writeAll(bytes);
}

/// Reads an NVPTX object in the format of `write`. Every `Mir.Target` of the result is a `.name`
/// target. The caller must run on a little-endian host.
pub fn read(gpa: Allocator, bytes: []const u8) ReadError!Object {
    assert(native_endian == .little);
    var r: Io.Reader = .fixed(bytes);
    return readObject(gpa, &r) catch |err| switch (err) {
        error.OutOfMemory => |e| e,
        error.EndOfStream, error.ReadFailed, error.InvalidObject => error.InvalidObject,
    };
}

fn readObject(gpa: Allocator, r: *Io.Reader) !Object {
    if (!std.mem.eql(u8, try r.takeArray(magic.len), magic)) return error.InvalidObject;
    if (try r.takeInt(u32, .little) != format_version) return error.InvalidObject;
    const ptx_version = try r.takeInt(u16, .little);
    const address_size = try r.takeInt(u16, .little);
    const target_bytes = try r.takeArray(target_len);
    const target = try gpa.dupe(u8, target_bytes[0 .. std.mem.findScalar(u8, target_bytes, 0) orelse target_len]);
    errdefer gpa.free(target);
    const compiler = try readBytes(gpa, r);
    errdefer gpa.free(compiler);
    const names = try gpa.alloc([]const u8, try readLen(r, @sizeOf(u32)));
    var names_read: usize = 0;
    errdefer {
        for (names[0..names_read]) |name| gpa.free(name);
        gpa.free(names);
    }
    for (names) |*name| {
        name.* = try readBytes(gpa, r);
        names_read += 1;
    }
    var lists: [3][]Item = @splat(&.{});
    var items_read: [3]usize = @splat(0);
    errdefer for (lists, items_read) |items, count| {
        for (items[0..count]) |*item| item.mir.deinit(gpa);
        gpa.free(items);
    };
    for (&lists, &items_read) |*items, *count| {
        items.* = try gpa.alloc(Item, try readLen(r, 2));
        for (items.*) |*item| {
            const linkage = std.enums.fromInt(Linkage, try r.takeByte()) orelse return error.InvalidObject;
            item.* = .{ .linkage = linkage, .mir = try readMir(gpa, r, names.len) };
            count.* += 1;
        }
    }
    const aliases = try gpa.alloc(Alias, try readLen(r, 2 * @sizeOf(u32)));
    errdefer gpa.free(aliases);
    for (aliases) |*alias| {
        alias.* = .{ .name = try readName(r, names.len), .function = try r.takeInt(u32, .little) };
        if (alias.function >= lists[2].len) return error.InvalidObject;
    }
    if (r.bufferedLen() != 0) return error.InvalidObject;
    return .{
        .ptx_version = ptx_version,
        .target = target,
        .address_size = address_size,
        .compiler = compiler,
        .externs = lists[0],
        .data = lists[1],
        .functions = lists[2],
        .aliases = aliases,
        .names = names,
    };
}

fn readMir(gpa: Allocator, r: *Io.Reader, name_count: usize) !Mir {
    const kind = std.enums.fromInt(Mir.Kind, try r.takeByte()) orelse return error.InvalidObject;
    const is_noinline = switch (try r.takeByte()) {
        0 => false,
        1 => true,
        else => return error.InvalidObject,
    };
    var mir: Mir = .{
        .kind = kind,
        .text = &.{},
        .prototype_len = 0,
        .relocs = &.{},
        .ptx_version = try r.takeInt(u16, .little),
        .is_noinline = is_noinline,
    };
    errdefer mir.deinit(gpa);
    mir.text = try readBytes(gpa, r);
    mir.prototype_len = try r.takeInt(u32, .little);
    if (mir.prototype_len > mir.text.len) return error.InvalidObject;
    mir.relocs = try gpa.alloc(Mir.Reloc, try readLen(r, 2 * @sizeOf(u32)));
    for (mir.relocs) |*reloc| {
        reloc.* = .{ .offset = try r.takeInt(u32, .little), .target = try readName(r, name_count) };
        if (reloc.offset > mir.text.len) return error.InvalidObject;
    }
    try r.readSliceAll(std.mem.sliceAsBytes(&mir.reg_counts));
    mir.label_count = try r.takeInt(u32, .little);
    var instructions: std.MultiArrayList(Mir.Inst) = .empty;
    try instructions.resize(gpa, try readLen(r, 8));
    mir.instructions = instructions.slice();
    for (mir.instructions.items(.tag)) |*tag| {
        tag.* = std.enums.fromInt(Mir.Inst.Tag, try r.takeByte()) orelse return error.InvalidObject;
    }
    for (mir.instructions.items(.ty)) |*ty| {
        ty.* = std.enums.fromInt(Mir.Type, try r.takeByte()) orelse return error.InvalidObject;
    }
    try r.readSliceAll(std.mem.sliceAsBytes(mir.instructions.items(.modifiers)));
    try r.readSliceAll(std.mem.sliceAsBytes(mir.instructions.items(.data)));
    mir.extra = try gpa.alloc(u32, try readLen(r, @sizeOf(u32)));
    try r.readSliceAll(std.mem.sliceAsBytes(mir.extra));
    mir.strings = try readBytes(gpa, r);
    mir.symbols = try gpa.alloc(Mir.Symbol, try readLen(r, @sizeOf(u32) + @sizeOf(u64)));
    for (mir.symbols) |*symbol| {
        symbol.* = .{ .target = try readName(r, name_count), .offset = try r.takeInt(u64, .little) };
    }
    mir.locals = try gpa.alloc(Mir.Local, try readLen(r, 2 * @sizeOf(u64)));
    for (mir.locals) |*local| {
        local.* = .{ .size = try r.takeInt(u64, .little), .alignment = try r.takeInt(u64, .little) };
    }
    return mir;
}

/// Reads a count, and rejects the count when the remaining bytes cannot hold that many elements.
fn readLen(r: *Io.Reader, min_size: usize) !usize {
    const len = try r.takeInt(u32, .little);
    if (len > r.bufferedLen() / min_size) return error.InvalidObject;
    return len;
}

fn readBytes(gpa: Allocator, r: *Io.Reader) ![]u8 {
    return gpa.dupe(u8, try r.take(try readLen(r, 1)));
}

fn readName(r: *Io.Reader, name_count: usize) !Mir.Target {
    const index = try r.takeInt(u32, .little);
    if (index >= name_count) return error.InvalidObject;
    return .{ .name = index };
}

fn testObject(gpa: Allocator) !Object {
    var instructions: std.MultiArrayList(Mir.Inst) = .empty;
    errdefer instructions.deinit(gpa);
    try instructions.append(gpa, .{ .tag = .mov, .ty = .b32, .data = 0 });
    try instructions.append(gpa, .{ .tag = .ret, .data = 0 });
    const function: Mir = .{
        .kind = .func,
        .text = try gpa.dupe(u8, ".func f()"),
        .prototype_len = 9,
        .relocs = try gpa.dupe(Mir.Reloc, &.{.{ .offset = 6, .target = .{ .name = 0 } }}),
        .ptx_version = 63,
        .is_noinline = true,
        .instructions = instructions.slice(),
        .extra = try gpa.dupe(u32, &.{ 0x10000, 0x50000007 }),
        .strings = try gpa.dupe(u8, "add.u32"),
        .symbols = try gpa.dupe(Mir.Symbol, &.{.{ .target = .{ .name = 1 }, .offset = 8 }}),
        .locals = try gpa.dupe(Mir.Local, &.{.{ .size = 16, .alignment = 8 }}),
        .reg_counts = .{ 0, 0, 1, 0, 0, 0 },
        .label_count = 2,
    };
    const data: Mir = .{
        .kind = .data,
        .text = try gpa.dupe(u8, ".global .u64 g = generic();\n"),
        .prototype_len = 0,
        .relocs = try gpa.dupe(Mir.Reloc, &.{
            .{ .offset = 13, .target = .{ .name = 1 } },
            .{ .offset = 25, .target = .{ .name = 0 } },
        }),
        .ptx_version = 60,
    };
    return .{
        .ptx_version = 63,
        .target = try gpa.dupe(u8, "sm_90a"),
        .address_size = 64,
        .compiler = try gpa.dupe(u8, "0.0.0-test"),
        .externs = try gpa.dupe(Item, &.{}),
        .data = try gpa.dupe(Item, &.{.{ .mir = data, .linkage = .visible }}),
        .functions = try gpa.dupe(Item, &.{.{ .mir = function, .linkage = .local }}),
        .aliases = try gpa.dupe(Alias, &.{.{ .name = .{ .name = 2 }, .function = 0 }}),
        .names = try gpa.dupe([]const u8, &.{ try gpa.dupe(u8, "f"), try gpa.dupe(u8, "g"), try gpa.dupe(u8, "h") }),
    };
}

fn writeAlloc(gpa: Allocator, object: *const Object) ![]u8 {
    var out: Io.Writer.Allocating = .init(gpa);
    defer out.deinit();
    try object.write(&out.writer, object);
    return out.toOwnedSlice();
}

test "read returns the object that write stored" {
    const gpa = std.testing.allocator;
    var object = try testObject(gpa);
    defer object.deinit(gpa);
    const bytes = try writeAlloc(gpa, &object);
    defer gpa.free(bytes);
    var copy = try read(gpa, bytes);
    defer copy.deinit(gpa);
    const again = try writeAlloc(gpa, &copy);
    defer gpa.free(again);
    try std.testing.expectEqualSlices(u8, bytes, again);
    try std.testing.expectEqualStrings("h", copy.names[copy.aliases[0].name.name]);
    try std.testing.expect(copy.functions[0].mir.is_noinline);
}

test "read rejects or survives every corruption of one byte" {
    const gpa = std.testing.allocator;
    var object = try testObject(gpa);
    defer object.deinit(gpa);
    const bytes = try writeAlloc(gpa, &object);
    defer gpa.free(bytes);
    for (bytes) |*byte| {
        const original = byte.*;
        for ([_]u8{ 0, 0xff, original +% 1 }) |corrupt| {
            byte.* = corrupt;
            var copy = read(gpa, bytes) catch |err| switch (err) {
                error.InvalidObject => continue,
                else => |e| return e,
            };
            copy.deinit(gpa);
        }
        byte.* = original;
    }
    try std.testing.expectError(error.InvalidObject, read(gpa, bytes[0 .. bytes.len - 1]));
    const longer = try std.mem.concat(gpa, u8, &.{ bytes, &.{0} });
    defer gpa.free(longer);
    try std.testing.expectError(error.InvalidObject, read(gpa, longer));
}

test "emit and write stop at a full writer" {
    const gpa = std.testing.allocator;
    var object = try testObject(gpa);
    defer object.deinit(gpa);
    var full: Io.Writer.Allocating = .init(gpa);
    defer full.deinit();
    try object.emit(gpa, &full.writer, &object);
    try std.testing.expect(std.mem.find(u8, full.written(), ".alias h, f;") != null);
    for (0..full.written().len) |len| {
        var buffer: [1024]u8 = undefined;
        var short: Io.Writer = .fixed(buffer[0..len]);
        try std.testing.expectError(error.WriteFailed, object.emit(gpa, &short, &object));
        try std.testing.expectEqualSlices(u8, full.written()[0..len], short.buffered());
    }
    const bytes = try writeAlloc(gpa, &object);
    defer gpa.free(bytes);
    for (0..bytes.len) |len| {
        var buffer: [1024]u8 = undefined;
        var short: Io.Writer = .fixed(buffer[0..len]);
        try std.testing.expectError(error.WriteFailed, object.write(&short, &object));
    }
}

test "read rejects a truncated object and another format version" {
    const gpa = std.testing.allocator;
    var object = try testObject(gpa);
    defer object.deinit(gpa);
    const bytes = try writeAlloc(gpa, &object);
    defer gpa.free(bytes);
    for (0..bytes.len) |len| {
        try std.testing.expectError(error.InvalidObject, read(gpa, bytes[0..len]));
    }
    bytes[magic.len] +%= 1;
    try std.testing.expectError(error.InvalidObject, read(gpa, bytes));
}
